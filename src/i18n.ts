export type UIKey = keyof typeof UI;

export function tr(key: UIKey, lang: Lang): string {
  return UI[key][lang];
}

/** Hook returning a translator bound to the current language. */
export function useT(): (key: UIKey) => string {
  const lang = useApp((s) => s.lang);
  return (key) => UI[key][lang];
}

/** Picks the current-language string from a bilingual content value. */
export function useL(): (v: L) => string {
  const lang = useApp((s) => s.lang);
  return (v) => v[lang];
}
